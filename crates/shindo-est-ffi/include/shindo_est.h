/*
 * C interface of shindo-est, which predicts JMA seismic intensities.
 *
 * - Ownership: a model handle is opened by the library and freed with its
 *   close function. Strings the library returns are static, or owned by the
 *   handle and valid until it is closed. Prediction results go into memory
 *   the caller allocates.
 * - Threads: a model handle may be shared by any number of threads for
 *   prediction, as long as no thread closes it meanwhile.
 * - Errors: functions that can fail return an int32_t code, SHINDO_EST_OK (0)
 *   for success. shindo_est_error_message() describes a code.
 * - Options: shindo_est_options starts with its own size, and every other
 *   field is 0 by default, so a C caller writes
 *   `shindo_est_options options = { .size = sizeof options };`. The library
 *   reads only the fields that fit in that size and takes defaults for the
 *   rest, and it rejects a nonzero field it does not know, so callers built
 *   against older or newer headers keep working.
 */

